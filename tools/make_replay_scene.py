"""Generate viewer/drone_replay_scene.js from viewer/drone_scene.js (same scene, replay mode switched on)."""
from pathlib import Path
v = Path(__file__).resolve().parents[1] / "viewer"
src = (v / "drone_scene.js").read_text(encoding="utf-8")
hdr = "// GENERATED by tools/make_replay_scene.py from drone_scene.js: do not edit, edit drone_scene.js instead.\nconst REPLAY_MODE = true;\n"
